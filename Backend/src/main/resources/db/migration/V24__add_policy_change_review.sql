-- Educational policy-servicing workflow: a request does not itself change coverage.
CREATE TABLE ins_policy_change_request (
    change_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL REFERENCES ins_policy(policy_id),
    requested_by BIGINT NOT NULL REFERENCES usr_user(user_id),
    quote_id BIGINT NOT NULL UNIQUE REFERENCES ins_quote(quote_id),
    idempotency_key VARCHAR(150) NOT NULL UNIQUE,
    consent_hash CHAR(64) NOT NULL,
    quote_snapshot_json JSONB NOT NULL,
    effective_at TIMESTAMPTZ NOT NULL,
    review_status VARCHAR(30) NOT NULL DEFAULT 'PENDING_REVIEW'
        CHECK(review_status IN ('PENDING_REVIEW','APPROVED','REJECTED','EXPIRED')),
    reviewed_by BIGINT REFERENCES usr_user(user_id),
    decision_reason VARCHAR(500),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_at TIMESTAMPTZ,
    scheduled_change_id BIGINT UNIQUE REFERENCES ins_policy_change(policy_change_id),
    CHECK(jsonb_typeof(quote_snapshot_json)='object'),
    CHECK(review_status NOT IN ('APPROVED','REJECTED') OR (reviewed_by IS NOT NULL AND decided_at IS NOT NULL)),
    CHECK(reviewed_by IS NULL OR reviewed_by <> requested_by)
);
CREATE UNIQUE INDEX ux_policy_change_pending ON ins_policy_change_request(policy_id)
    WHERE review_status='PENDING_REVIEW';
CREATE INDEX ix_policy_change_review_queue ON ins_policy_change_request(review_status,effective_at,change_request_id);
