CREATE TABLE public.ins_terms_document (
    terms_document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_code VARCHAR(100) NOT NULL,
    document_version VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
    source_type VARCHAR(30) NOT NULL,
    source_uri VARCHAR(512),
    source_hash CHAR(64) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    status VARCHAR(30) NOT NULL,
    is_simulation BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_ins_terms_document_version UNIQUE (document_code, document_version),
    CONSTRAINT chk_ins_terms_document_hash CHECK (source_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_ins_terms_document_period CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT chk_ins_terms_document_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'RETIRED'))
);

CREATE TABLE public.ins_terms_clause (
    terms_clause_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    terms_document_id BIGINT NOT NULL,
    clause_code VARCHAR(50) NOT NULL,
    title VARCHAR(255) NOT NULL,
