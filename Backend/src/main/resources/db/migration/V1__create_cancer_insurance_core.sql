-- CapSure 교육용 암보험 금융 프로세스의 additive schema.
-- 기존 subscription/product_source 구조를 삭제하거나 변경하지 않는다.

CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

