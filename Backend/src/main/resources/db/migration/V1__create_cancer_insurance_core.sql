        FOREIGN KEY (terms_document_id) REFERENCES public.ins_terms_document (terms_document_id),
    CONSTRAINT uk_ins_terms_clause_code UNIQUE (terms_document_id, clause_code),
    CONSTRAINT chk_ins_terms_clause_page CHECK (page_no IS NULL OR page_no > 0),
    CONSTRAINT chk_ins_terms_clause_sort CHECK (sort_order > 0)
);

CREATE TABLE public.ins_product_version (
