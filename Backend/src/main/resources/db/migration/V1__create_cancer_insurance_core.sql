CREATE TABLE public.ops_reconciliation (
    reconciliation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type VARCHAR(50) NOT NULL,
    target_id VARCHAR(100) NOT NULL,
    provider VARCHAR(30) NOT NULL,
    local_status VARCHAR(50) NOT NULL,
    provider_status VARCHAR(50) NOT NULL,
    result VARCHAR(30) NOT NULL,
    details_json JSONB NOT NULL DEFAULT '{}'::JSONB,
    executed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_ops_reconciliation_result CHECK (result IN ('MATCHED', 'CORRECTED', 'STILL_UNKNOWN', 'FAILED'))
);

CREATE TABLE public.ops_job_execution (
    job_execution_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name VARCHAR(100) NOT NULL,
    instance_key VARCHAR(255) NOT NULL,
    execution_no INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL,
    checkpoint_json JSONB NOT NULL DEFAULT '{}'::JSONB,
    input_count BIGINT NOT NULL DEFAULT 0,
    accepted_count BIGINT NOT NULL DEFAULT 0,
    duplicate_count BIGINT NOT NULL DEFAULT 0,
    quarantined_count BIGINT NOT NULL DEFAULT 0,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at TIMESTAMPTZ,
    error_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_ops_job_execution UNIQUE (job_name, instance_key, execution_no),
    CONSTRAINT chk_ops_job_execution_no CHECK (execution_no > 0),
    CONSTRAINT chk_ops_job_status CHECK (status IN ('STARTING', 'RUNNING', 'COMPLETED', 'FAILED', 'STOPPED')),
    CONSTRAINT chk_ops_job_counts CHECK (
        input_count >= 0 AND accepted_count >= 0 AND duplicate_count >= 0 AND quarantined_count >= 0
    )
);

CREATE TABLE public.ops_quarantine (
    quarantine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_execution_id BIGINT NOT NULL,
    source_key VARCHAR(255) NOT NULL,
    reason_code VARCHAR(100) NOT NULL,
    raw_hash CHAR(64) NOT NULL,
    raw_payload_json JSONB NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_ops_quarantine_execution
        FOREIGN KEY (job_execution_id) REFERENCES public.ops_job_execution (job_execution_id),
    CONSTRAINT uk_ops_quarantine_source UNIQUE (job_execution_id, source_key),
    CONSTRAINT chk_ops_quarantine_hash CHECK (raw_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_ops_quarantine_status CHECK (status IN ('PENDING', 'RESOLVED', 'IGNORED'))
);

