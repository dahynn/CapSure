CREATE TABLE ins_policy_change (
    policy_change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_id BIGINT NOT NULL REFERENCES ins_policy(policy_id),
    quote_id BIGINT NOT NULL UNIQUE REFERENCES ins_quote(quote_id),
    policy_version_id BIGINT NOT NULL UNIQUE REFERENCES ins_policy_version(policy_version_id),
    effective_at TIMESTAMPTZ NOT NULL,
    idempotency_key VARCHAR(150) NOT NULL UNIQUE,
    consent_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(policy_id, effective_at)
);
CREATE INDEX idx_ins_policy_version_effective ON ins_policy_version(policy_id, valid_from, valid_to);

ALTER TABLE ins_premium_receivable ADD COLUMN policy_version_id BIGINT REFERENCES ins_policy_version(policy_version_id);
